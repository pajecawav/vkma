/**
 * Emits the handwritten-by-generator pieces of `src/generated`:
 * `version.ts`, `enum-names.ts` and the per-target `index.ts` barrels.
 */

import { readdir, readFile } from "node:fs/promises";
import path from "node:path";
import { enumKey, pascal } from "./naming.ts";
import type { EnumNamesEntry } from "./transform.ts";

const HEADER = "// @generated by @vkma.dev/api-schema scripts/generate.ts — DO NOT EDIT";

/** `exportSuffix` json2code is configured with for the validator targets. */
export const EXPORT_SUFFIX = "Schema";

function byLocale(a: string, b: string): number {
	return a.localeCompare(b);
}

export function renderVersionModule(version: string): string {
	return [
		HEADER,
		"",
		`/** VK API version this package was generated from. */`,
		`export const API_VERSION = ${JSON.stringify(version)};`,
		"",
	].join("\n");
}

export function renderEnumNamesModule(entries: readonly EnumNamesEntry[]): string {
	const blocks = entries.map(entry => {
		const constName = `${pascal(entry.defName)}EnumNames`;
		const used = new Set<string>();
		const members = entry.names.map((name, index) => {
			let key = enumKey(name);
			if (key === "" || used.has(key)) {
				key = `${key}_${index + 1}`;
			}
			used.add(key);
			const value = entry.values[index];
			const prop = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : JSON.stringify(key);
			return `\t${prop}: ${JSON.stringify(value)},`;
		});
		return [
			`// ${entry.defName}`,
			`export const ${constName} = {`,
			...members,
			"} as const;",
		].join("\n");
	});
	return [
		HEADER,
		"",
		`/** Human-readable name maps for VK API enums (\`enum\` + \`enumNames\`). */`,
		"",
		blocks.join("\n\n"),
		"",
	].join("\n");
}

export interface MethodMapEntry {
	/** Dotted VK method name (`ads.getAccounts`). */
	readonly dotted: string;
	/** Section directory the method lives in. */
	readonly section: string;
	/** Params definition name (`ads_getAccounts_params`). */
	readonly paramsDef: string;
	/** Attributed response definition names, sorted; empty when undocumented. */
	readonly responses: readonly string[];
}

export type EmitTarget = "typescript" | "zod" | "valibot";

/**
 * Emit `method-map.ts` for a target: a lookup from dotted method names to
 * params/response types (typescript, an interface) or schemas (validator
 * targets, a `MethodSchemas` const). The runtime `response` slot holds the
 * base variant (`<method>_response`); extended variants (`…_extended_response`
 * and friends) stay available as their own exports.
 */
export function renderMethodMapModule(
	entries: readonly MethodMapEntry[],
	target: EmitTarget,
): string {
	const typeOnly = target === "typescript";
	const suffix = typeOnly ? "" : EXPORT_SUFFIX;
	// In validator targets the exported `…Schema` type alias describes the
	// PARSED shape, not the schema value — wrap it in the runtime schema type.
	const schemaType = (ref: string): string =>
		target === "zod" ? `z.ZodType<${ref}>` : `v.GenericSchema<unknown, ${ref}>`;
	const exportName = (defName: string): string => `${pascal(defName)}${suffix}`;
	/**
	 * Response defs referenced by this target: typescript unions every variant,
	 * validator maps hold the base variant (`<method>_response`) — or the first
	 * documented variant when the schema has no base response for the method.
	 */
	const referencedResponses = (entry: MethodMapEntry): readonly string[] => {
		if (typeOnly) {
			return entry.responses;
		}
		const base = entry.responses.find(
			def => def === `${entry.dotted.replaceAll(".", "_")}_response`,
		);
		return [base ?? entry.responses[0]].filter(def => def !== undefined);
	};
	const imports = new Map<string, Set<string>>();
	const addImport = (file: string, exportName_: string): void => {
		const names = imports.get(file) ?? new Set<string>();
		names.add(exportName_);
		imports.set(file, names);
	};
	for (const entry of entries) {
		addImport(`./${entry.section}/methods.js`, exportName(entry.paramsDef));
		for (const def of referencedResponses(entry)) {
			addImport(`./${entry.section}/responses.js`, exportName(def));
		}
	}

	const lines: string[] = [HEADER, ""];
	if (target === "zod") {
		lines.push(`import { z } from "zod";`);
	} else if (target === "valibot") {
		lines.push(`import * as v from "valibot";`);
	}
	for (const [file, names] of [...imports].toSorted((a, b) => byLocale(a[0], b[0]))) {
		const keyword = typeOnly ? "import type" : "import";
		lines.push(`${keyword} { ${[...names].toSorted(byLocale).join(", ")} } from "${file}";`);
	}
	lines.push("");

	const sorted = [...entries].toSorted((a, b) => byLocale(a.dotted, b.dotted));
	if (typeOnly) {
		lines.push("/** Typed lookup of every documented VK API method. */");
		lines.push("export interface MethodMap {");
		for (const entry of sorted) {
			lines.push(`\t"${entry.dotted}": {`);
			lines.push(`\t\tparams: ${exportName(entry.paramsDef)};`);
			if (entry.responses.length > 0) {
				lines.push(`\t\tresponse: ${entry.responses.map(exportName).join(" | ")};`);
			}
			lines.push("\t};");
		}
		lines.push("}", "");
		return lines.join("\n");
	}

	lines.push("/** Runtime lookup of every documented VK API method's schemas. */");
	lines.push("export interface MethodSchemas {");
	for (const entry of sorted) {
		lines.push(`\t"${entry.dotted}": {`);
		lines.push(`\t\tparams: ${schemaType(exportName(entry.paramsDef))};`);
		const [response] = referencedResponses(entry);
		if (response !== undefined) {
			lines.push(`\t\tresponse: ${schemaType(exportName(response))};`);
		}
		lines.push("\t};");
	}
	lines.push("}", "");
	// An explicit annotation keeps the serialized declaration under the
	// compiler's inference limit (TS7056 with 569 entries).
	lines.push("export const MethodSchemas: MethodSchemas = {");
	for (const entry of sorted) {
		lines.push(`\t"${entry.dotted}": {`);
		lines.push(`\t\tparams: ${exportName(entry.paramsDef)},`);
		const [response] = referencedResponses(entry);
		if (response !== undefined) {
			lines.push(`\t\tresponse: ${exportName(response)},`);
		}
		lines.push("\t},");
	}
	lines.push("};", "");
	return lines.join("\n");
}

export interface BarrelExtras {
	/** Export `API_VERSION` from `./version.js`. */
	readonly version: boolean;
	/** EnumNames constant names to export from `./enum-names.js`. */
	readonly enumNames: readonly string[];
	/** Export the method map from `./method-map.js`. */
	readonly methodMap: boolean;
}

/**
 * Build a barrel `index.ts` for a generated target directory by scanning the
 * generated section files and re-exporting every export except each file's
 * junk root export (`Objects` / `Methods` / `Responses`, plus the suffix).
 *
 * `typeOnly` emits `export type { … }` statements (typescript target); the
 * validator targets export runtime values alongside their inferred types.
 */
export async function buildBarrel(
	targetDir: string,
	suffix: string,
	extras: BarrelExtras,
	typeOnly: boolean,
): Promise<string> {
	const keyword = typeOnly ? "export type {" : "export {";
	const lines: string[] = [HEADER, ""];
	const sections = (await readdir(targetDir, { withFileTypes: true }))
		.filter(e => e.isDirectory())
		.map(e => e.name)
		.toSorted(byLocale);

	for (const section of sections) {
		for (const stem of ["methods", "objects", "responses"]) {
			const file = path.join(targetDir, section, `${stem}.ts`);
			const names = await exportNames(file, `${pascal(stem)}${suffix}`);
			if (names.length === 0) {
				continue;
			}
			lines.push(
				keyword,
				...names.map(n => `\t${n},`),
				`} from "./${section}/${stem}.js";`,
				"",
			);
		}
	}

	if (extras.version) {
		lines.push(`export { API_VERSION } from "./version.js";`, "");
	}
	if (extras.methodMap) {
		lines.push(
			typeOnly
				? `export type { MethodMap } from "./method-map.js";`
				: `export { MethodSchemas } from "./method-map.js";`,
			"",
		);
	}
	if (extras.enumNames.length > 0) {
		lines.push(
			`export {`,
			...[...new Set(extras.enumNames)].toSorted(byLocale).map(n => `\t${n},`),
			`} from "./enum-names.js";`,
			"",
		);
	}
	return lines.join("\n");
}

/** Parse `export const/type …` names from a generated file, minus the junk root export. */ async function exportNames(
	file: string,
	junk: string,
): Promise<string[]> {
	let content: string;
	try {
		content = await readFile(file, "utf8");
	} catch {
		return [];
	}
	const names = new Set<string>();
	for (const match of content.matchAll(/^export (?:const|type) ([A-Za-z0-9_$]+)/gm)) {
		const name = match[1];
		if (name && name !== junk) {
			names.add(name);
		}
	}
	return [...names].toSorted(byLocale);
}
