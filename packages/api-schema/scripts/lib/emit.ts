/**
 * Emits the handwritten-by-generator pieces of `src/generated`:
 * `version.ts`, `enum-names.ts` and the per-target `index.ts` barrels.
 */

import { readdir, readFile } from "node:fs/promises";
import path from "node:path";
import { enumKey, pascal } from "./naming.ts";
import type { EnumNamesEntry } from "./transform.ts";

const HEADER = "// @generated by @vkma.dev/api-schema scripts/generate.ts — DO NOT EDIT";

function byLocale(a: string, b: string): number {
	return a.localeCompare(b);
}

export function renderVersionModule(version: string): string {
	return [
		HEADER,
		"",
		`/** VK API version this package was generated from. */`,
		`export const API_VERSION = ${JSON.stringify(version)};`,
		"",
	].join("\n");
}

export function renderEnumNamesModule(entries: readonly EnumNamesEntry[]): string {
	const blocks = entries.map(entry => {
		const constName = `${pascal(entry.defName)}EnumNames`;
		const used = new Set<string>();
		const members = entry.names.map((name, index) => {
			let key = enumKey(name);
			if (key === "" || used.has(key)) {
				key = `${key}_${index + 1}`;
			}
			used.add(key);
			const value = entry.values[index];
			const prop = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : JSON.stringify(key);
			return `\t${prop}: ${JSON.stringify(value)},`;
		});
		return [
			`// ${entry.defName}`,
			`export const ${constName} = {`,
			...members,
			"} as const;",
		].join("\n");
	});
	return [
		HEADER,
		"",
		`/** Human-readable name maps for VK API enums (\`enum\` + \`enumNames\`). */`,
		"",
		blocks.join("\n\n"),
		"",
	].join("\n");
}

export interface BarrelExtras {
	/** Export `API_VERSION` from `./version.js`. */
	readonly version: boolean;
	/** EnumNames constant names to export from `./enum-names.js`. */
	readonly enumNames: readonly string[];
}

/**
 * Build a barrel `index.ts` for a generated target directory by scanning the
 * generated section files and re-exporting every export except each file's
 * junk root export (`Objects` / `Methods` / `Responses`, plus the suffix).
 *
 * `typeOnly` emits `export type { … }` statements (typescript target); the
 * validator targets export runtime values alongside their inferred types.
 */
export async function buildBarrel(
	targetDir: string,
	suffix: string,
	extras: BarrelExtras,
	typeOnly: boolean,
): Promise<string> {
	const keyword = typeOnly ? "export type {" : "export {";
	const lines: string[] = [HEADER, ""];
	const sections = (await readdir(targetDir, { withFileTypes: true }))
		.filter(e => e.isDirectory())
		.map(e => e.name)
		.sort(byLocale);

	for (const section of sections) {
		for (const stem of ["methods", "objects", "responses"]) {
			const file = path.join(targetDir, section, `${stem}.ts`);
			const names = await exportNames(file, `${pascal(stem)}${suffix}`);
			if (names.length === 0) {
				continue;
			}
			lines.push(
				keyword,
				...names.map(n => `\t${n},`),
				`} from "./${section}/${stem}.js";`,
				"",
			);
		}
	}

	if (extras.version) {
		lines.push(`export { API_VERSION } from "./version.js";`, "");
	}
	if (extras.enumNames.length > 0) {
		lines.push(
			`export {`,
			...[...new Set(extras.enumNames)].sort(byLocale).map(n => `\t${n},`),
			`} from "./enum-names.js";`,
			"",
		);
	}
	return lines.join("\n");
}

/** Parse `export const/type …` names from a generated file, minus the junk root export. */
async function exportNames(file: string, junk: string): Promise<string[]> {
	let content: string;
	try {
		content = await readFile(file, "utf8");
	} catch {
		return [];
	}
	const names = new Set<string>();
	for (const match of content.matchAll(/^export (?:const|type) ([A-Za-z0-9_$]+)/gm)) {
		const name = match[1];
		if (name && name !== junk) {
			names.add(name);
		}
	}
	return [...names].sort(byLocale);
}
