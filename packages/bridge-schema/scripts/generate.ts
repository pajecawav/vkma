/**
 * Generates `src/` from `schema/events.json`:
 *
 * 1. json2code (typescript target, `naming: "origin"`) renders every `$defs`
 *    entry into `src/generated/typescript/events.ts`.
 * 2. Emits `src/generated/schema-data.ts` — the catalogue document as typed
 *    data behind the `./schema` entrypoint.
 * 3. Emits `src/index.ts` — the package root. The three catalogue maps are
 *    declared as `interface`s IN THIS MODULE on purpose: declaration merging
 *    (`declare module "@vkma.dev/bridge-schema"`) only works against the
 *    module that declares the interface, so consumers can extend the
 *    catalogue with their own events (upstream's `type` aliases cannot be
 *    merged — extending is our differentiator).
 *
 * Run via `pnpm generate` from the package root (part of build/test/dev).
 */

import { readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { generate } from "@pajecawav/json2code";

const pkgRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schemaFile = path.join(pkgRoot, "schema", "events.json");
const generatedDir = path.join(pkgRoot, "src", "generated");

const HEADER = "// @generated by @vkma.dev/bridge-schema scripts/generate.ts — DO NOT EDIT";

interface WiringEntry {
	readonly result: string;
	readonly failed: string;
}

interface CatalogueDoc {
	readonly $defs: Readonly<Record<string, unknown>>;
	readonly "x-vkma-catalogue": {
		readonly props: Readonly<Record<string, string>>;
		readonly receive: Readonly<Record<string, string>>;
		readonly events: Readonly<Record<string, WiringEntry>>;
	};
}

async function main(): Promise<void> {
	const doc = JSON.parse(await readFile(schemaFile, "utf8")) as CatalogueDoc;
	const defNames = Object.keys(doc.$defs).toSorted((a, b) => a.localeCompare(b));
	const { props, receive, events } = doc["x-vkma-catalogue"];

	await rm(generatedDir, { recursive: true, force: true });
	const { written, deleted, diagnostics } = await generate({
		input: schemaFile,
		output: generatedDir,
		targets: ["typescript"],
		options: {
			naming: "origin",
			rootExports: false,
		},
		clean: true,
	});
	for (const diagnostic of diagnostics) {
		console.warn(`generate: ${diagnostic.code} ${diagnostic.message}`);
	}

	await writeFile(path.join(generatedDir, "schema-data.ts"), renderSchemaData(doc));
	await writeFile(
		path.join(pkgRoot, "src", "index.ts"),
		renderIndex(defNames, props, receive, events),
	);

	console.log(
		`generate: ${String(written)} files written (${String(deleted)} cleaned) — defs: ${defNames.length}, methods: ${Object.keys(props).length}, receive: ${Object.keys(receive).length}, wiring: ${Object.keys(events).length}`,
	);
}

/** `src/generated/schema-data.ts` — the raw catalogue as typed data. */
function renderSchemaData(doc: CatalogueDoc): string {
	return [
		HEADER,
		"",
		"/** The wiring tables: method → props definition, event → data definition,",
		" * method → its Result/Failed event names. Definition names reference",
		" * `$defs` of the same document. */",
		"export interface EventsCatalogue {",
		"\treadonly props: Readonly<Record<string, string>>;",
		"\treadonly receive: Readonly<Record<string, string>>;",
		"\treadonly events: Readonly<Record<string, { readonly result: string; readonly failed: string }>>;",
		"}",
		"",
		"/** The whole catalogue document: JSON Schema `$defs` plus the wiring tables. */",
		"export interface EventsSchemaDocument {",
		"\treadonly $schema: string;",
		"\treadonly title: string;",
		"\treadonly description: string;",
		"\treadonly $defs: Readonly<Record<string, unknown>>;",
		`\treadonly "x-vkma-catalogue": EventsCatalogue;`,
		"}",
		"",
		`export const eventsSchema: EventsSchemaDocument = ${JSON.stringify(doc, null, "\t")};`,
		"",
		'export const catalogue: EventsCatalogue = eventsSchema["x-vkma-catalogue"];',
		"",
	].join("\n");
}

/** `src/index.ts` — the augmentation-able package root. */
function renderIndex(
	defNames: readonly string[],
	props: Readonly<Record<string, string>>,
	receive: Readonly<Record<string, string>>,
	events: Readonly<Record<string, WiringEntry>>,
): string {
	const referenced = [...new Set([...Object.values(props), ...Object.values(receive)])].toSorted(
		(a, b) => a.localeCompare(b),
	);
	const module = '"./generated/typescript/events.js"';
	const importType = (names: readonly string[]): string =>
		`import type {\n${names.map(n => `\t${n},`).join("\n")}\n} from ${module};`;
	const exportType = (names: readonly string[]): string =>
		`export type {\n${names.map(n => `\t${n},`).join("\n")}\n} from ${module};`;

	const interfaceOf = (
		name: string,
		comment: string,
		members: readonly string[],
		render: (key: string) => string,
	): string =>
		[
			`/** ${comment} */`,
			`export interface ${name} {`,
			...members
				.toSorted((a, b) => a.localeCompare(b))
				.map(key => `\t${memberKey(key)}: ${render(key)};`),
			"}",
		].join("\n");

	return [
		HEADER,
		"//",
		"// The catalogue maps below are `interface`s declared in this root module",
		'// on purpose: `declare module "@vkma.dev/bridge-schema"` merges ONLY into',
		"// the module that declares the interface. Extend the catalogue with your",
		"// own events like this:",
		"//",
		'//   declare module "@vkma.dev/bridge-schema" {',
		"//     interface RequestPropsMap {",
		"//       VKWebAppMyCustomMethod: { foo: string };",
		"//     }",
		"//     interface ReceiveDataMap {",
		"//       VKWebAppMyCustomMethodResult: { bar: number };",
		"//     }",
		"//     interface ReceiveEventMap {",
		"//       VKWebAppMyCustomMethod: {",
		'//         result: "VKWebAppMyCustomMethodResult";',
		'//         failed: "VKWebAppMyCustomMethodFailed";',
		"//       };",
		"//     }",
		"//   }",
		"",
		`/** The @vkontakte/vk-bridge release this catalogue was extracted from. */`,
		"",
		importType(referenced),
		"",
		exportType(defNames),
		"",
		interfaceOf(
			"RequestPropsMap",
			"Request props of every sendable VK Bridge method. Extend via `declare module`. See the header.",
			Object.keys(props),
			key => props[key] ?? "never",
		),
		"",
		interfaceOf(
			"ReceiveDataMap",
			"Data of every receivable VK Bridge event (method responses keyed by the method name, plus receive-only pushes). Extend via `declare module`.",
			Object.keys(receive),
			key => receive[key] ?? "never",
		),
		"",
		interfaceOf(
			"ReceiveEventMap",
			"Wiring of a method to its Result/Failed event names. Extend via `declare module`.",
			Object.keys(events),
			key => {
				const entry = events[key];
				return entry
					? `{ result: ${JSON.stringify(entry.result)}; failed: ${JSON.stringify(entry.failed)} }`
					: "never";
			},
		),
		"",
	].join("\n");
}

/** Interface members with non-identifier keys still quote correctly. */
function memberKey(key: string): string {
	return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : JSON.stringify(key);
}

await main();
